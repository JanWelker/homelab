#!/usr/bin/env python3
"""Render the Authentik sign-in branding into a ConfigMap.

Writes payload/platform/authentik/branding.yaml with two files the server
serves under /static/dist/custom/:

- background.svg: isometric containers in the logo's colours on a pale sky,
  shaded at the top and bottom edges where Authentik puts white text.
- logo.svg: docs/assets/images/logo.png wrapped in a 160 px wide SVG, so the
  card shows it at that size and sharp on high-density screens.

The layout comes from a fixed random seed, so a rerun reproduces the file.

    uv run python scripts/authentik-branding.py
"""

import base64
import pathlib
import random

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOGO = ROOT / 'docs/assets/images/logo.png'
OUT = ROOT / 'payload/platform/authentik/branding.yaml'

W, H = 1920, 1080
# Logo colours; docs/stylesheets/extra.css names them.
BLUE, BLUE_D, BLUE_L, HI = '#305484', '#23405f', '#4878a8', '#609CCC'
GREEN, GREEN_D = '#54A854', '#357f35'
SHADES = [
    (BLUE_L, BLUE, BLUE_D),
    (HI, BLUE_L, BLUE),
    ('#6fc46f', GREEN, GREEN_D),
    ('#8a9bb0', '#5f7187', '#45556a'),
]
WEIGHTS = [0.42, 0.3, 0.12, 0.16]


def container(ax: float, ay: float, top: str, left: str, right: str) -> str:
    """One 2:1 isometric container; (ax, ay) is its front bottom corner."""
    length, depth, height = 180, 80, 70
    a, b = (ax, ay), (ax + length, ay - length / 2)
    c = (ax + length - depth, ay - length / 2 - depth / 2)
    e = (ax - depth, ay - depth / 2)

    def up(p):
        return (p[0], p[1] - height)

    def pts(*ps):
        return ' '.join(f'{x:.1f},{y:.1f}' for x, y in ps)

    ribs = ''.join(
        f'<line x1="{ax + length * t:.1f}" y1="{ay - length * t / 2:.1f}" '
        f'x2="{ax + length * t:.1f}" y2="{ay - length * t / 2 - height:.1f}" '
        'stroke="#000" stroke-opacity="0.13" stroke-width="2"/>'
        for t in [i / 8 for i in range(1, 8)]
    )
    return (
        f'<polygon points="{pts(e, a, up(a), up(e))}" fill="{left}"/>'
        f'<polygon points="{pts(a, b, up(b), up(a))}" fill="{right}"/>{ribs}'
        f'<polygon points="{pts(up(e), up(a), up(b), up(c))}" fill="{top}"/>'
    )


def background() -> str:
    rnd = random.Random(3)
    lines = []
    for row in range(9):
        for col in range(-2, 14):
            if rnd.random() < 0.45:
                continue
            x, y = col * 210 - row * 120 + 60, 330 + row * 95
            for level in range(rnd.randint(1, 3)):
                top, left, right = rnd.choices(SHADES, WEIGHTS)[0]
                lines.append(container(x, y - level * 70, top, left, right))

    def stop(offset, color, opacity=1):
        return f'<stop offset="{offset}" stop-color="{color}" stop-opacity="{opacity}"/>'

    def gradient(name, *stops):
        head = f'<linearGradient id="{name}" x1="0" y1="0" x2="0" y2="1">'
        return head + ''.join(stops) + '</linearGradient>'

    navy = '#14223a'
    return '\n'.join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" '
            'preserveAspectRatio="xMidYMid slice">',
            '<defs>',
            gradient('sky', stop(0, '#dfe9f4'), stop(1, '#b7cbe0')),
            gradient(
                'edge',
                stop(0, navy, 0.6),
                stop(0.12, navy, 0),
                stop(0.86, navy, 0),
                stop(1, navy, 0.6),
            ),
            '</defs>',
            f'<rect width="{W}" height="{H}" fill="url(#sky)"/>',
            '<g opacity="0.88">',
            *lines,
            '</g>',
            f'<rect width="{W}" height="{H}" fill="url(#edge)"/>',
            '</svg>',
        ]
    )


def logo() -> str:
    png = base64.b64encode(LOGO.read_bytes()).decode()
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
        'width="160" height="136" viewBox="0 0 400 340">\n'
        f'<image width="400" height="340" xlink:href="data:image/png;base64,{png}"/>\n'
        '</svg>'
    )


def block(text: str) -> str:
    return '\n'.join('    ' + line for line in text.splitlines())


OUT.write_text(
    '---\n'
    '# Generated by scripts/authentik-branding.py; see docs/platform/authentik.md#branding\n'
    'apiVersion: v1\n'
    'kind: ConfigMap\n'
    'metadata:\n'
    '  name: authentik-branding\n'
    'data:\n'
    '  background.svg: |\n'
    f'{block(background())}\n'
    '  logo.svg: |\n'
    f'{block(logo())}\n'
)
print(OUT.relative_to(ROOT), OUT.stat().st_size // 1024, 'KiB')
