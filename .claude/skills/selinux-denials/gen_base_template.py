#!/usr/bin/env python3
r"""Build selinuxd's base_container template from a node's own policy modules.

Dump every module of a node, each line prefixed with its module name:

    ssh <node> 'sudo sh -c "cd /var/lib/selinux/mcs/active/modules/400 && for m in *; do
      (bzcat \$m/cil 2>/dev/null || cat \$m/cil) | sed \"s|^|\$m: |\"; done"' > modules.cil
    uv run python gen_base_template.py modules.cil > base_container.cil

A type that inherits the `container` block then gets every rule Flatcar grants
container_t: on Flatcar most of them sit on the type itself, not on the
container_domain attribute the upstream template relies on. The other modules
are read only to see which attributes exist. Regenerate after a Flatcar update
that changes the container policy.
"""

import re
import sys

SOCKET_PERMS = 'create open getattr setattr read write rename link unlink ioctl lock append'
KEY_PERMS = 'create link read search setattr view write'


def main():
    with open(sys.argv[1], encoding='utf-8') as handle:
        text = handle.read()
    lines = [line.split(': ', 1)[1] for line in text.split('\n') if line.startswith('container: ')]
    declared = set(re.findall(r'\(typeattribute ([a-z0-9_]+)\)', text))
    attrs, top, optional = set(), set(), set()
    for line in lines:
        rule = line.strip()
        if not re.search(r'\bcontainer_t\b', rule) or rule.count('(') != rule.count(')'):
            continue
        member = re.match(r'\(typeattributeset ([a-z0-9_]+) \(([^()]*)\)\)$', rule)
        if member:
            if 'container_t' in member.group(2).split() and member.group(1) in declared:
                attrs.add(member.group(1))
            continue
        if re.match(r'\((allow|dontaudit|allowx|auditallow) ', rule):
            rule = re.sub(r'\bcontainer_t\b', 'process', rule)
            # Indented in the module means inside an optional block.
            (optional if line.startswith((' ', '\t')) else top).add(rule)
    attrs.discard('mlsrangetrans')
    out = [
        "; Generated by gen_base_template.py from the node's container module: a",
        '; type that inherits this block gets what container_t has. Regenerate',
        '; after a Flatcar update that changes the container policy.',
        '(block container',
        '(type process)',
        '(type socket)',
        '(roletype system_r process)',
    ]
    out += [f'(typeattributeset {attr} (process ))' for attr in sorted(attrs)]
    out += [
        '(typeattributeset file_type (socket ))',
        f'(allow process socket (sock_file ({SOCKET_PERMS})))',
        '(allow process cpu_online_t (file (getattr open read)))',
        f'(allow container_runtime_t process (key ({KEY_PERMS})))',
    ]
    out += sorted(top)
    out += [
        f'(optional base_container_optional_{index}\n    {rule}\n)'
        for index, rule in enumerate(sorted(optional - top))
    ]
    out.append(')')
    print('\n'.join(out))
    counts = f'attributes={len(attrs)} rules={len(top)} optional={len(optional - top)}'
    print(counts, file=sys.stderr)


if __name__ == '__main__':
    main()
